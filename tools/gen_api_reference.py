#!/usr/bin/env python3
"""Generate the API reference page (reference/units.md) from the Fortran
sources of the GRABNES code repository, using Ford as the parser.

Usage:
    uv run python tools/gen_api_reference.py [--src PATH] [--out PATH]

The sources are only read, never modified: Ford is run on a normalized copy
in a temporary directory where ordinary ``!`` comments are removed (Ford
would otherwise mistake them for documentation comments); ``!!`` Ford doc
comments are kept. The two cpp template fragments (``mem_temp.f90``,
``MIO/MPI/mpi_type.f90``) are include files with ``[_TYPE]`` placeholders and
are skipped.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# ---------------------------------------------------------------------------
# Source normalization


def strip_comments(text: str) -> str:
    """Drop ordinary ``!`` comments; keep ``!!`` lines (Ford documentation).

    A ``!`` inside a quoted string does not start a comment.
    """
    out = []
    for line in text.splitlines():
        in_str: str | None = None
        cut = -1
        for i, ch in enumerate(line):
            if in_str:
                if ch == in_str:
                    in_str = None
            elif ch in "\"'":
                in_str = ch
            elif ch == "!":
                cut = i
                break
        if cut < 0:
            out.append(line)
            continue
        stripped = line.lstrip()
        if stripped.startswith("!!"):
            out.append(line[: cut] + line[cut:].rstrip("\n"))  # keep as-is
        elif cut == 0 or not line[:cut].strip():
            pass  # whole-line comment: drop
        else:
            out.append(line[:cut].rstrip())  # inline comment: cut
    return "\n".join(out) + "\n"


TEMPLATE_FRAGMENTS = {"mem_temp.f90", "mpi_type.f90"}


def normalize_tree(src: Path, dst: Path) -> None:
    for f in sorted(src.rglob("*")):
        if not f.is_file() or f.suffix.lower() not in (".f90",):
            continue
        if f.name in TEMPLATE_FRAGMENTS:
            continue
        target = dst / f.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(strip_comments(f.read_text(errors="replace")))


# ---------------------------------------------------------------------------
# Extraction


def var_str(v) -> str:
    bits = [v.vartype or v.type or ""]
    attrs = [a for a in getattr(v, "attribs", []) if a]
    if getattr(v, "intent", ""):
        attrs.insert(0, f"intent({v.intent})")
    if getattr(v, "optional", False) and "optional" not in attrs:
        attrs.append("optional")
    decl = ", ".join(b for b in [bits[0]] + attrs if b)
    init = getattr(v, "initial", None)
    if init:
        decl += f" = {init}"
    return f"`{v.name}` — {decl}" if decl.strip() else f"`{v.name}`"


def proc_sig(p) -> str:
    args = getattr(p, "args", None)
    argstr = ", ".join(a.name for a in args) if args else ""
    kind = "function" if type(p).__name__ == "FortranFunction" else "subroutine"
    res = ""
    if kind == "function":
        r = getattr(p, "result", None)
        rt = ""
        if r is not None:
            rt = getattr(r, "vartype", "") or getattr(r, "type", "") or ""
            if getattr(r, "attribs", None):
                rt = (rt + ", " + ", ".join(r.attribs)).strip(", ")
        res = f" result({r.name}): {rt}" if r is not None and rt else ""
    return f"{kind} {p.name}({argstr}){res}"


def collect_docs(p) -> list[str]:
    """Return cleaned lines of a procedure's ``!!`` documentation block."""
    doc = (getattr(p, "doc", "") or "").strip()
    if not doc:
        return []
    lines = []
    for ln in doc.splitlines():
        ln = ln.strip().lstrip("!").strip()
        ln = re.sub(r"^@\s*(details|par|return|author|date|version)\s*:?.*", "", ln).strip()
        if ln:
            lines.append(ln)
    return lines


# ---------------------------------------------------------------------------
# Rendering


def render(units, programs, src, commit, ford_version):
    used_labels: set[str] = set()
    today = dt.date.today().isoformat()
    out = [
        "(api-units)=\n# Fortran unit reference\n",
        "```{note}\n"
        "This page is generated by `tools/gen_api_reference.py` (Ford "
        f"{ford_version}) from the sources at commit `{commit}` on {today}.\n"
        "Do not edit by hand — regenerate after code changes. Public "
        "procedures and module variables are listed; argument meanings are "
        "documented in the source comments.\n```\n",
    ]
    out.append("| Unit | Kind | Source |\n|---|---|---|")
    for kind, u in programs + units:
        out.append(f"| {u.name} | {kind} | `{u.filename}` |")
    out.append("")
    for kind, u in programs + units:
        label = f"api-{u.name.lower()}"
        if label in used_labels:
            stem = Path(str(u.filename)).stem.lower()
            label = f"api-{u.name.lower()}-{stem}"
        used_labels.add(label)
        out.append(f"({label})=\n## {u.name}  ({u.filename})\n")
        out.append(f"- Kind: {kind}\n- Source: `{u.filename}`")
        if getattr(u, "uses", None):
            def use_names(d):
                if isinstance(d, str):
                    # raw source fragment: "mod, only : a, b" -> "mod"
                    head = d.split(",")[0].split("(")[0].strip()
                    return [] if not head or head.lower().startswith("only") else [head]
                if isinstance(d, (list, tuple, set)):
                    return [n for x in d for n in use_names(x)]
                return [getattr(d, "name", str(d)).strip()]

            used = sorted({n for d in u.uses for n in use_names(d) if n})
            out.append(f"- Uses: {', '.join(f'`{m}`' for m in used)}")
        out.append("")
        procs = [
            p
            for p in getattr(u, "pub_procs", {}).values()
            if type(p).__name__ in ("FortranSubroutine", "FortranFunction")
        ]
        gens = [
            p
            for p in getattr(u, "pub_procs", {}).values()
            if p not in procs
        ]
        if procs:
            out.append("### Public procedures\n")
            for p in sorted(procs, key=lambda x: x.name.lower()):
                out.append(f"- `{proc_sig(p)}`")
                for ln in collect_docs(p)[:3]:
                    out.append(f"    {ln}")
            out.append("")
        if gens:
            names = ", ".join(f"`{g.name}`" for g in sorted(gens, key=lambda x: x.name.lower()))
            out.append(f"### Generic interfaces\n\n{names}\n")
        varnames = [
            v
            for v in getattr(u, "pub_vars", {}).values()
            if not type(v).__name__.startswith("FortranNamelist")
        ]
        if varnames:
            out.append("### Public module variables\n")
            for v in sorted(varnames, key=lambda x: x.name.lower()):
                out.append(f"- {var_str(v)}")
            out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------------------


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", default="../grabnes/lanczosKuboCode/Src")
    ap.add_argument("--out", default="reference/units.md")
    a = ap.parse_args()

    src = Path(a.src).resolve()
    if not src.is_dir():
        sys.exit(f"source directory not found: {src}")
    import ford

    commit = "unknown"
    try:
        commit = subprocess.run(
            ["git", "-C", src, "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:
        pass

    from ford import ProjectSettings
    from ford.fortran_project import Project

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        normalize_tree(src, tmp)
        settings = ProjectSettings(
            src_dir=[tmp], extensions=["f90"], preprocessor="",
        )
        project = Project(settings)
        units = [("module", m) for m in sorted(project.modules, key=lambda m: m.name.lower())]
        programs = [("program", g) for g in sorted(project.programs, key=lambda g: g.name.lower())]
        text = render(units, programs, src, commit, ford.__version__)

    Path(a.out).write_text(text)
    n = sum(1 for ln in text.splitlines() if ln.startswith("## "))
    print(f"wrote {a.out}: {n} units")
    return 0


if __name__ == "__main__":
    sys.exit(main())
